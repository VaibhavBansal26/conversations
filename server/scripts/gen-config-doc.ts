// Renders docs/CONFIGURATION.md from the zod config schema (types, defaults, optionality) plus src/configMeta.ts (descriptions, security notes).
//   npx tsx scripts/gen-config-doc.ts          write
//   npx tsx scripts/gen-config-doc.ts --check  exit 1 when the committed file is stale
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { z } from "zod";
import { configSchema } from "../src/config.js";
import { CONFIG_META } from "../src/configMeta.js";

export function renderConfigDoc(): string {
  const shape = configSchema.shape as Record<string, z.ZodType>;
  const names = Object.keys(shape);
  const missing = names.filter((n) => !CONFIG_META[n]);
  const extra = Object.keys(CONFIG_META).filter((n) => !shape[n]);
  if (missing.length || extra.length) throw new Error(`configMeta.ts out of step with config.ts. Undocumented: ${missing.join(", ") || "-"}. Documented but not in the schema: ${extra.join(", ") || "-"}`);
  const json = z.toJSONSchema(configSchema, { io: "input", unrepresentable: "any", target: "draft-2020-12" }) as { properties: Record<string, { type?: string; enum?: string[]; default?: unknown; minimum?: number; maximum?: number; exclusiveMinimum?: number }> };
  const defaults = configSchema.safeParse({}).data as Record<string, unknown> | undefined;
  const groups = new Map<string, string[]>();
  for (const n of names) {
    const m = CONFIG_META[n]!;
    const p = json.properties[n] ?? {};
    const def = defaults?.[n];
    const isBool = !!p.enum && p.enum.length === 4 && p.enum.includes("true") && p.enum.includes("0");
    const type = isBool ? "boolean" : p.enum ? p.enum.map((e) => `\`${e}\``).join(" \\| ") : typeof def === "boolean" ? "boolean" : typeof def === "number" || p.type === "number" || p.type === "integer" ? (p.type === "integer" ? "integer" : "number") : p.type === "string" || typeof def === "string" ? "string" : "string";
    const range = [p.minimum !== undefined ? `min ${p.minimum}` : "", p.exclusiveMinimum !== undefined ? `> ${p.exclusiveMinimum}` : "", p.maximum !== undefined && p.maximum < Number.MAX_SAFE_INTEGER ? `max ${p.maximum}` : ""].filter(Boolean).join(", ");
    const dflt = def === undefined ? "unset" : `\`${String(def)}\``;
    const required = n === "JWT_SECRET" ? "production" : "no";
    const notes = [m.secret ? "**Secret.**" : "", m.note ?? ""].filter(Boolean).join(" ");
    const row = `| \`${n}\` | ${type}${range ? ` (${range})` : ""} | ${dflt} | ${required} | ${m.example ? `\`${m.example}\`` : ""} | ${m.desc}${notes ? ` ${notes}` : ""} |`;
    (groups.get(m.group) ?? groups.set(m.group, []).get(m.group)!).push(row);
  }
  const body = [...groups.entries()].map(([g, rows]) => `## ${g}\n\n| Variable | Type | Default | Required | Example | Description |\n| --- | --- | --- | --- | --- | --- |\n${rows.join("\n")}\n`).join("\n");
  return `# Configuration

<!-- Generated by \`npm run docs:config\` from server/src/config.ts and server/src/configMeta.ts. Do not edit by hand: \`docs:check\` fails when it is stale. -->

Every setting is an environment variable, validated at start-up by a zod schema (\`server/src/config.ts\`); an invalid value stops the process with a message naming the variable. Defaults make \`npm run dev\` work with no environment at all. Booleans accept \`true|false|1|0\`. There are **${names.length}** variables; the ones marked **Secret** must come from your secret store, never from the repository.

Start-up cross-checks: \`SMS_PROVIDER=twilio\` needs the Twilio credentials, \`EMAIL_PROVIDER=sendgrid\` needs \`SENDGRID_API_KEY\`, \`SOCKET_ADAPTER=redis\` or \`JOB_QUEUE=bullmq\` need \`REDIS_URL\`, \`DATABASE_URL\` must be a \`postgres://\` URL, \`STRIPE_SECRET_KEY\` needs \`STRIPE_WEBHOOK_SECRET\`, and production needs \`JWT_SECRET\`.

${body}`;
}

if (process.argv[1]?.endsWith("gen-config-doc.ts")) {
  const out = new URL("../../docs/CONFIGURATION.md", import.meta.url);
  const text = renderConfigDoc();
  if (process.argv.includes("--check")) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
      console.error("stale: docs/CONFIGURATION.md (run `npm run docs:config`)");
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(`wrote docs/CONFIGURATION.md (${Object.keys(CONFIG_META).length} variables)`);
  }
}
